// Generates src/data/lessons.js: each concept's verified body text cut into
// lesson-player screens ("beats"). The text is never rewritten here, only cut
// at sentence boundaries, so the audited content stays intact and every beat
// is a string literal the read-aloud backend can verify (content-hashes.json).
//
//   node scripts/build-lessons.cjs          write src/data/lessons.js
//   node scripts/build-lessons.cjs --dump   print numbered sentences per concept
//
// Authored structure lives in src/data/lessonPlans.json, keyed by module name,
// positional per concept: { "lead": "...", "beats": [["Head.", nSentences], ...] }
// Concepts without a plan fall back to two sentences per screen, no heads.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'src/App.jsx'), 'utf8').replace(/\r\n/g, '\n');
const at = src.indexOf('const MODULES = ');
const start = src.indexOf('{', at), end = src.indexOf('\n};', start);
const MODULES = JSON.parse(src.slice(start, end + 2));

const ABBR = /\b(vs|e\.g|i\.e|etc|U\.S|Dr|Mr|Mrs|Ms|No|St|cf|approx)\.$/;
function sentences(body) {
  const out = []; let cur = '';
  body.split(/(?<=[.?!][)"”’]?)\s+(?=[A-Z0-9("“‘])/).forEach(p => {
    cur = cur ? cur + ' ' + p : p;
    const open = (cur.match(/\(/g) || []).length - (cur.match(/\)/g) || []).length;
    if (ABBR.test(cur) || open > 0) return;
    out.push(cur); cur = '';
  });
  if (cur) out.push(cur);
  return out;
}

if (process.argv.includes('--dump')) {
  for (const [name, m] of Object.entries(MODULES)) {
    console.log('\n### ' + name);
    m.concepts.forEach((c, i) => { console.log(`\n[${i}] ${c.title}`); sentences(c.body).forEach((s, k) => console.log(`  ${k + 1}. ${s}`)); });
  }
  process.exit(0);
}

const planPath = path.join(root, 'src/data/lessonPlans.json');
const plans = fs.existsSync(planPath) ? JSON.parse(fs.readFileSync(planPath, 'utf8')) : {};
const LESSONS = {}; let authored = 0, total = 0; const problems = [];
for (const [name, m] of Object.entries(MODULES)) {
  LESSONS[name] = m.concepts.map((c, i) => {
    total++;
    const ss = sentences(c.body), plan = plans[name]?.[i];
    if (ss.join(' ') !== c.body.trim().replace(/\s+/g, ' ') && ss.join(' ') !== c.body.trim()) problems.push(`${name}[${i}] sentence split does not round-trip`);
    if (plan) {
      const n = plan.beats.reduce((a, b) => a + b[1], 0);
      if (n !== ss.length) { problems.push(`${name}[${i}] "${c.title}": plan covers ${n} sentences, body has ${ss.length}`); }
      else { authored++; let k = 0; return { lead: plan.lead || null, beats: plan.beats.map(([head, cnt]) => ({ head, text: ss.slice(k, k += cnt).join(' ') })) }; }
    }
    const beats = []; for (let k = 0; k < ss.length; k += 2) beats.push({ head: null, text: ss.slice(k, k + 2).join(' ') });
    return { lead: null, beats };
  });
}
if (problems.length) { console.error(problems.join('\n')); if (process.argv.includes('--strict')) process.exit(1); }
fs.writeFileSync(path.join(root, 'src/data/lessons.js'),
  '// GENERATED by scripts/build-lessons.cjs from MODULES + src/data/lessonPlans.json. Do not edit by hand.\n' +
  'export const LESSONS = ' + JSON.stringify(LESSONS, null, 1) + ';\n');
console.log(`lessons.js written: ${total} concepts, ${authored} with authored plans, ${problems.length} problems`);
